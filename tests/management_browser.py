"""Includes the four existing online checks plus full-management workflows."""
import json
import secrets
from pathlib import Path
import unittest
from playwright.sync_api import expect
import online_browser


class ManagementBrowserTests(online_browser.OnlineBrowserTests):
    def tab(self, name):
        self.page.locator(f'[data-action="manager-tab"][data-tab="{name}"]').click()

    def save_form(self, name):
        self.page.locator(f'[data-form="{name}"] [type="submit"]').click()

    def test_05_create_cards_and_packs_and_purchase_with_live_rates(self):
        self.owner()
        self.tab('cards')
        self.page.locator('[data-action="manager-new"]').click()
        form = self.page.locator('[data-form="manager-catalog"]')
        card_name = 'Hồ "Sao" <mới>'
        form.locator('[name="name"]').fill(card_name)
        form.locator('[name="cost"]').fill('0')
        form.locator('[name="attack"]').fill('9')
        form.locator('[name="health"]').fill('11')
        form.locator('[name="skill"]').select_option('swift')
        form.locator('[name="description"]').fill('<img src=x onerror=alert(1)>')
        self.save_form('manager-catalog')
        expect(self.page.locator('[data-form="manager-catalog"]')).to_have_count(0)
        search = self.page.locator('[data-form="manager-search"]')
        search.locator('[name="query"]').fill(card_name)
        self.save_form('manager-search')
        expect(self.page.locator('.manager-table tbody tr')).to_have_count(1)
        expect(self.page.locator('.manager-table tbody strong')).to_have_text(card_name)
        expect(self.page.locator('.manager-table img')).to_have_count(0)
        self.page.screenshot(path='/tmp/linh-thu-screenshots/manager-cards.png', full_page=True)
        self.tab('packs')
        self.page.locator('[data-action="manager-new"]').click()
        form = self.page.locator('[data-form="manager-catalog"]')
        form.locator('[name="name"]').fill('Pack Huyền Thoại Mới')
        form.locator('[name="price"]').fill('17')
        form.locator('[name="guarantee"]').select_option('legendary')
        for key, value in [('common','0'),('rare','0'),('epic','0'),('legendary','100')]:
            form.locator(f'[name="weight-{key}"]').fill(value)
        self.save_form('manager-catalog')
        expect(self.page.locator('[data-form="manager-catalog"]')).to_have_count(0)
        player = self.new_page()
        self.register(player, 'alice')
        tile = player.locator('.pack-tile').filter(has_text='Pack Huyền Thoại Mới')
        tile.locator('[data-action="buy-pack"]').click()
        expect(player.locator('.reveal-card')).to_have_count(5)
        expect(player.locator('.reveal-card.legendary')).to_have_count(5)
        self.assertEqual(self.profile(player)['profile']['coins'], 1183)

